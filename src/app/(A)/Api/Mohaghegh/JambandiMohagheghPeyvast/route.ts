import { NextRequest, NextResponse } from "next/server";
import sql from "mssql";

import { getConnection } from "@/Lib/db";
import { verifyToken } from "@/Lib/auth";

export async function POST(req: NextRequest) {
    const token = req.cookies.get("token")?.value;
    if (!token) {
        return NextResponse.json(
            { status: 401, error: "Unauthorized: No token" },
            { status: 401 }
        );
    }
    const body = await req.json();
    const { tahghighid, fileName, fileExtend, fileSize, userid } = body;

    try {
        verifyToken(token);
    } catch {
        return NextResponse.json(
            { status: 401, error: "Unauthorized: Invalid or expired token" },
            { status: 401 }
        );
    }

    try {
        const pool = await getConnection();
        const result = await pool
            .request()
            .input("TahghighId", sql.BigInt, tahghighid)
            .input("FileName", sql.NVarChar(200), fileName)
            .input("FileExtend", sql.NVarChar(200), fileExtend)
            .input("FileSize", sql.NVarChar, fileSize)
            .input("UserId", sql.Int, userid)
            .execute("Tahghighat.SP_Insert_Tahghigh_JambandiPeyvast");

        return NextResponse.json(
            { status: 200, data: result.recordset }
        );

    } catch (err) {
        return NextResponse.json(
            { error: err instanceof Error ? err.message : "Unknown error" },
            { status: 500 }
        );
    }
}
